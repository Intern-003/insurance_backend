<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class PolicyRenewal extends Model
{
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | POLICY IDS
        |--------------------------------------------------------------------------
        */

        'proposal_id',

        'renewed_proposal_id',

        /*
        |--------------------------------------------------------------------------
        | POLICY NUMBERS
        |--------------------------------------------------------------------------
        */

        'old_policy_number',

        'new_policy_number',

        /*
        |--------------------------------------------------------------------------
        | DATES
        |--------------------------------------------------------------------------
        */

        'renewal_date',

        'old_expiry_date',

        'new_expiry_date',

        /*
        |--------------------------------------------------------------------------
        | PREMIUM
        |--------------------------------------------------------------------------
        */

        'renewal_tenure',

        'premium_amount',

        /*
        |--------------------------------------------------------------------------
        | PAYMENT
        |--------------------------------------------------------------------------
        */

        'transaction_id',

        'payment_status',

        /*
        |--------------------------------------------------------------------------
        | STATUS
        |--------------------------------------------------------------------------
        */

        'status',

        /*
        |--------------------------------------------------------------------------
        | RIDERS
        |--------------------------------------------------------------------------
        */

        'selected_riders',
    ];

    /*
    |--------------------------------------------------------------------------
    | CASTS
    |--------------------------------------------------------------------------
    */

    protected $casts = [

        'selected_riders' => 'array',

        'renewal_date' => 'date',

        'old_expiry_date' => 'date',

        'new_expiry_date' => 'date',
    ];

    /*
    |--------------------------------------------------------------------------
    | RELATIONS
    |--------------------------------------------------------------------------
    */

    public function proposal()
    {
        return $this->belongsTo(
            InsuranceProposal::class,
            'proposal_id'
        );
    }

    public function renewedProposal()
    {
        return $this->belongsTo(
            InsuranceProposal::class,
            'renewed_proposal_id'
        );
    }
}